const products = [];
let n = 0;
for (const [category, { items }] of Object.entries(catalog)) {
  for (const [name, price, description, imageQuery] of items) {
    n++;
    products.push({
      name,
      slug: slug(name),
      category,
      price,
      description,
      stockQuantity: 20 + ((n * 37) % 181), // deterministic 20-200
      imageQuery: imageQuery || name,
    });
  }
}
const categories = Object.entries(catalog).map(([name, { description }]) => ({
  name,
  description,
}));
fs.writeFileSync(
  "data/products.json",
  JSON.stringify({ categories, products }, null, 2),
);
const csv = ["name,category,price,stockQuantity,description,imageFile"].concat(
  products.map((p) =>
    [
      p.name,
      p.category,
      p.price,
      p.stockQuantity,
      p.description,
      `${p.slug}.jpg`,
    ]
      .map((v) => `"${String(v).replace(/"/g, '""')}"`)
      .join(","),
  ),
);
fs.writeFileSync("data/products.csv", csv.join("\n"));
